import { describe, expect, it } from "vitest";
import { stripClaudeLinks } from "../../scripts/strip-claude-links.mjs";

describe("stripClaudeLinks", () => {
  it("drops commit trailers", () => {
    const message = [
      "Add CI",
      "",
      "Runs lint and tests.",
      "",
      "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
      "Claude-Session: https://claude.ai/code/session_01ABC",
      "",
    ].join("\n");
    expect(stripClaudeLinks(message)).toBe("Add CI\n\nRuns lint and tests.");
  });

  it("drops a PR footer with its rule", () => {
    const body = "Docs only.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01ABC)_";
    expect(stripClaudeLinks(body)).toBe("Docs only.");
    expect(stripClaudeLinks("Fix.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n")).toBe("Fix.");
  });

  it("leaves other text alone, including mentions of Claude Code", () => {
    const text = "Runs your signed-in Claude Code CLI (`claude -p`).\n\n---\n\nSee https://code.claude.com for setup.\n";
    expect(stripClaudeLinks(text)).toBe(text);
    expect(stripClaudeLinks("")).toBe("");
    // The address written out as text (not a link) is kept.
    const prose = "- strips any claude.ai/code or claude.com/claude-code link from commit messages.";
    expect(stripClaudeLinks(prose)).toBe(prose);
  });

  it("keeps the paragraphs around a link in the middle", () => {
    expect(stripClaudeLinks("One.\n\nhttps://claude.ai/code/session_x\n\nTwo.")).toBe("One.\n\nTwo.");
  });
});
